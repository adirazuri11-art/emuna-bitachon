// ============================================================
// scripts/gen-search-index.cjs
// מייצר את lib/search-index.json — הקרנה רזה של הקטלוג (רק שדות שהלקוח צריך
// לחיפוש, למאתר-המתנה ולכרטיס-מוצר). מקור אמת יחיד: PRODUCTS (lib/catalog).
//
// רץ כ-prebuild (ראה package.json) — לכן האינדקס לעולם לא יוצא-סנכרון: כל build
// מקמפל מחדש את catalog.ts ומקרין אותו. אין רשימה ידנית.
//
// שלב 1 (חיצוני): tsc -p tsconfig.gen.json → .gen-build/**.js
// שלב 2 (כאן): טוענים את הקטלוג המקומפל דרך hook שממפה '@/…' ומקרינים.
// ============================================================

const fs = require('fs');
const path = require('path');
const Module = require('module');

const ROOT = process.cwd();
const GEN = path.join(ROOT, '.gen-build');

// --- hook: ממפה ייבוא '@/…' אל הפלט המקומפל (JS) או אל קובץ המקור (JSON) ---
const origResolve = Module._resolveFilename;
Module._resolveFilename = function (request, ...rest) {
  if (request.startsWith('@/')) {
    const rel = request.slice(2); // אחרי '@/'
    if (rel.endsWith('.json')) {
      return path.join(ROOT, rel); // JSON נשאר מקור אמיתי
    }
    const candidate = path.join(GEN, rel + '.js');
    if (fs.existsSync(candidate)) return candidate;
    const asDir = path.join(GEN, rel, 'index.js');
    if (fs.existsSync(asDir)) return asDir;
    return path.join(GEN, rel); // ליפול חזרה לרזולוציה הרגילה
  }
  return origResolve.call(this, request, ...rest);
};

const compiledCatalog = path.join(GEN, 'lib', 'catalog.js');
if (!fs.existsSync(compiledCatalog)) {
  console.error('[gen-search-index] missing compiled catalog:', compiledCatalog);
  console.error('  run: tsc -p tsconfig.gen.json  first');
  process.exit(1);
}

const { PRODUCTS } = require(compiledCatalog);
if (!Array.isArray(PRODUCTS) || PRODUCTS.length === 0) {
  console.error('[gen-search-index] PRODUCTS empty/not-array');
  process.exit(1);
}

// --- הקרנה רזה: רק מה שחיפוש / מאתר-מתנה / כרטיס-מוצר / QuickView צורכים ---
function slimVariantGroups(vgs) {
  if (!Array.isArray(vgs)) return undefined;
  const out = [];
  for (const g of vgs) {
    const opts = (g.options || [])
      .filter((o) => o && o.hex)
      .map((o) => ({ id: o.id, label: o.label, hex: o.hex }));
    if (opts.length) out.push({ id: g.id, label: g.label, options: opts });
  }
  return out.length ? out : undefined;
}

function project(p) {
  const lite = {
    id: p.id,
    sku: p.sku,
    slug: p.slug,
    titleHe: p.titleHe,
    category: p.category,
    basePrice: p.basePrice,
    isCustomizable: !!p.isCustomizable,
    iconKey: p.iconKey,
    shortDescription: p.shortDescription || '',
    tags: Array.isArray(p.tags) ? p.tags : [],
    stockStatus: p.stockStatus,
    badges: Array.isArray(p.badges) ? p.badges : [],
    hasCustomization: !!p.customization,
  };
  // אופציונליים — נכללים רק כשקיימים (חוסך משקל)
  if (p.imageUrl) lite.imageUrl = p.imageUrl;
  if (p.material) lite.material = p.material;
  if (typeof p.discountPrice === 'number') lite.discountPrice = p.discountPrice;
  if (p.certification) lite.certification = p.certification;
  if (p.isNew) lite.isNew = true;
  if (typeof p.stockLeft === 'number') lite.stockLeft = p.stockLeft;
  if (typeof p.minOrderUnits === 'number') lite.minOrderUnits = p.minOrderUnits;
  if (p.logoOverlay) lite.logoOverlay = true;
  if (p.subcategory) lite.subcategory = p.subcategory;
  if (p.priceType) lite.priceType = p.priceType;
  if (Array.isArray(p.prepTimeDays)) lite.prepTimeDays = p.prepTimeDays;
  if (Array.isArray(p.audience) && p.audience.length) lite.audience = p.audience;
  if (Array.isArray(p.occasions) && p.occasions.length) lite.occasions = p.occasions;
  const vg = slimVariantGroups(p.variantGroups);
  if (vg) lite.variantGroups = vg;
  return lite;
}

const items = PRODUCTS.map(project);
const outPath = path.join(ROOT, 'lib', 'search-index.json');
const payload = { _note: 'AUTO-GENERATED by scripts/gen-search-index.cjs — do not edit by hand', count: items.length, items };
fs.writeFileSync(outPath, JSON.stringify(payload));
const kb = (fs.statSync(outPath).size / 1024).toFixed(0);
console.log('[gen-search-index] wrote', items.length, 'items →', outPath, '(' + kb + 'KB)');
